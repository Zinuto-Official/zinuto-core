import fs from 'node:fs';
import path from 'node:path';
import { ROOT_DIR, readRegistry, selectProvider } from './connector-registry.mjs';

const checkOnly = process.argv.slice(2).every((argument) => argument === '--check');
if (!checkOnly && process.argv.length > 2) {
  throw new Error('Usage: market-data:generate-runtime-versions [--check]');
}

const registry = readRegistry();
const versions = Object.fromEntries(
  ['aktools', 'akshare', 'ccxt', 'financedatareader'].map((providerId) => [
    providerId,
    selectProvider(registry, providerId).version,
  ]),
);
const typescriptPath = path.join(
  ROOT_DIR,
  'apps',
  'desktop',
  'local-api',
  'src',
  'application',
  'market-data-acquisition',
  'marketDataConnectorVersions.generated.ts',
);
const financeDataReaderVersionPath = path.join(
  ROOT_DIR,
  'apps',
  'desktop',
  'local-api',
  'sidecars',
  'finance-datareader',
  'connector-versions.json',
);
const typeScriptContents = `// SPDX-License-Identifier: GPL-3.0-only\n\n` +
  `// Generated by tools/market-data/generate-runtime-version-manifest.mjs.\n` +
  `// Do not edit by hand; the audited connector registry is authoritative.\n` +
  `export const MARKET_DATA_CONNECTOR_VERSIONS = ${JSON.stringify(versions, null, 2)} as const;\n` +
  `export const AKTOOLS_VERSION = MARKET_DATA_CONNECTOR_VERSIONS.aktools;\n` +
  `export const AKSHARE_VERSION = MARKET_DATA_CONNECTOR_VERSIONS.akshare;\n` +
  `export const CCXT_VERSION = MARKET_DATA_CONNECTOR_VERSIONS.ccxt;\n` +
  `export const FINANCE_DATA_READER_VERSION = MARKET_DATA_CONNECTOR_VERSIONS.financedatareader;\n`;
const financeDataReaderContents = `${JSON.stringify({
  schemaVersion: 1,
  financedatareader: versions.financedatareader,
}, null, 2)}\n`;

const assertOrWrite = (filePath, contents) => {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (current === contents) return;
  if (checkOnly) {
    throw new Error(`MARKET_DATA_RUNTIME_VERSION_MANIFEST_DRIFT:${path.relative(ROOT_DIR, filePath)}`);
  }
  fs.writeFileSync(filePath, contents);
};

assertOrWrite(typescriptPath, typeScriptContents);
assertOrWrite(financeDataReaderVersionPath, financeDataReaderContents);
process.stdout.write(`${JSON.stringify({ generated: checkOnly ? false : true, versions }, null, 2)}\n`);
