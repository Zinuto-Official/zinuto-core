import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
);
const contractPath = path.join(
  root,
  "contracts/openapi/desktop-local-api.v1.yaml",
);
const authorityPath = path.join(root, "contracts/endpoint-effects.v1.json");
const consumerPath = path.join(
  root,
  "apps/desktop/web/src/api/backendEndpointEffects.generated.ts",
);
const args = new Set(process.argv.slice(2));
const write = args.has("--write");
const methods = new Set(["delete", "get", "patch", "post", "put"]);

const contractBytes = fs.readFileSync(contractPath);
const contract = YAML.parse(contractBytes.toString("utf8"));
const inventory = Object.entries(contract.paths ?? {})
  .flatMap(([routePath, item]) =>
    Object.entries(item ?? {}).flatMap(([method, operation]) =>
      methods.has(method) && operation && typeof operation === "object"
        ? [
            {
              key: `${method.toUpperCase()} ${routePath}`,
              method: method.toUpperCase(),
              path: routePath,
            },
          ]
        : [],
    ),
  )
  .sort((left, right) => left.key.localeCompare(right.key));

if (!fs.existsSync(authorityPath)) {
  throw new Error("Endpoint effect authority is missing.");
}
const authority = JSON.parse(fs.readFileSync(authorityPath, "utf8"));
if (authority.schemaVersion !== 1 || !Array.isArray(authority.endpoints)) {
  throw new Error("Endpoint effect authority has an invalid schema.");
}
const authorityKeys = authority.endpoints.map(
  (entry) => `${entry.method} ${entry.path}`,
);
const inventoryKeys = inventory.map((entry) => entry.key);
if (JSON.stringify(authorityKeys) !== JSON.stringify(inventoryKeys)) {
  const authorityKeySet = new Set(authorityKeys);
  const inventoryKeySet = new Set(inventoryKeys);
  const missing = inventoryKeys.filter((key) => !authorityKeySet.has(key));
  const extra = authorityKeys.filter((key) => !inventoryKeySet.has(key));
  throw new Error(
    `Endpoint effect authority does not classify the exact OpenAPI operation inventory; missing=${JSON.stringify(missing)}, extra=${JSON.stringify(extra)}. Classify effects explicitly before generation.`,
  );
}
for (const entry of authority.endpoints) {
  if (
    !["read", "write"].includes(entry.effect) ||
    !Array.isArray(entry.invalidationScopes) ||
    !Array.isArray(entry.workspaceIds) ||
    (entry.effect === "read" &&
      (entry.invalidationScopes.length || entry.workspaceIds.length))
  ) {
    throw new Error(
      `Endpoint effect declaration is invalid: ${entry.method} ${entry.path}`,
    );
  }
}

const expectedOpenapiSha256 = crypto
  .createHash("sha256")
  .update(contractBytes)
  .digest("hex");
const normalizedAuthority = {
  ...authority,
  openapiSha256: expectedOpenapiSha256,
};
const authorityText = `${JSON.stringify(normalizedAuthority, null, 2)}\n`;
const endpointRows = normalizedAuthority.endpoints
  .map((entry) => `  ${JSON.stringify(entry)},`)
  .join("\n");
const consumerText = `// SPDX-License-Identifier: GPL-3.0-only
// Generated by tools/contracts/generate-endpoint-effects.mjs. Do not edit.

export type BackendEndpointEffect = {
  method: string;
  path: string;
  effect: "read" | "write";
  invalidationScopes: readonly string[];
  workspaceIds: readonly string[];
};

export const BACKEND_ENDPOINT_EFFECTS = [
${endpointRows}
] as const satisfies readonly BackendEndpointEffect[];
`;

if (write) {
  fs.writeFileSync(authorityPath, authorityText);
  fs.writeFileSync(consumerPath, consumerText);
  console.log(
    `[endpoint-effects] generated ${inventory.length} explicit endpoint effects.`,
  );
} else {
  if (fs.readFileSync(authorityPath, "utf8") !== authorityText) {
    throw new Error(
      "Endpoint effect authority OpenAPI hash is stale. Run npm run contract:generate.",
    );
  }
  if (
    !fs.existsSync(consumerPath) ||
    fs.readFileSync(consumerPath, "utf8") !== consumerText
  ) {
    throw new Error(
      "Endpoint effect consumer metadata is stale. Run npm run contract:generate.",
    );
  }
  console.log(
    `[endpoint-effects] ${inventory.length} explicit endpoint effects are current.`,
  );
}
