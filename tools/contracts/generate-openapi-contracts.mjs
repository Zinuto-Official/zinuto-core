import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildOpenApiZodModule,
  readOpenApiDocument,
} from "./openapi-zod-generator.mjs";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(SCRIPT_DIR, "../..");
const DESKTOP_OPENAPI_PATH = path.join(
  ROOT_DIR,
  "contracts",
  "openapi",
  "desktop-local-api.v1.yaml",
);
const DESKTOP_OUTPUT_PATH = path.join(
  ROOT_DIR,
  "packages",
  "shared",
  "src",
  "contracts-desktop",
  "http-api.ts",
);
const DESKTOP_API_PATH = path.join(
  ROOT_DIR,
  "packages",
  "shared",
  "src",
  "contracts-desktop",
  "api.ts",
);
const DESKTOP_OPENAPI_ZOD_OUTPUT_PATH = path.join(
  ROOT_DIR,
  "packages",
  "shared",
  "src",
  "contracts-desktop",
  "openapi-zod.generated.ts",
);
const RUNTIME_SCHEMA_OUTPUT_PATH = path.join(
  ROOT_DIR,
  "contracts",
  "runtime-response-schemas.v1.json",
);

const OPENAPI_METHODS = new Set(["get", "post", "put", "patch", "delete"]);
const GENERATED_SCHEMA_MAP_COMMENT =
  "// This route-schema map is generated by tools/contracts/generate-openapi-contracts.mjs.";

const checkOnly = process.argv.includes("--check");

const readText = (filePath) => fs.readFileSync(filePath, "utf8");

const extractBasePath = (sourceText, fallback) => {
  const match = sourceText.match(/^\s+basePath:\s*(\S+)\s*$/mu);
  return match ? match[1].trim() : fallback;
};

const extractOpenApiPaths = (sourceText) => {
  const paths = [];
  const lines = sourceText.split(/\r?\n/u);
  let inPaths = false;
  for (const line of lines) {
    if (/^paths:\s*$/u.test(line)) {
      inPaths = true;
      continue;
    }
    if (!inPaths) {
      continue;
    }
    if (/^[^\s]/u.test(line) && !/^paths:\s*$/u.test(line)) {
      break;
    }
    const pathMatch = line.match(/^  (?:("[^"]+")|(\/[^:]+)):\s*$/u);
    if (pathMatch) {
      paths.push(pathMatch[1] ? JSON.parse(pathMatch[1]) : pathMatch[2]);
    }
  }
  return paths;
};

const extractOpenApiOperations = (sourceText) => {
  const operations = [];
  const lines = sourceText.split(/\r?\n/u);
  let inPaths = false;
  let currentPath = null;
  let currentOperation = null;

  const finishOperation = () => {
    if (currentOperation) {
      operations.push(currentOperation);
      currentOperation = null;
    }
  };

  for (const line of lines) {
    if (/^paths:\s*$/u.test(line)) {
      inPaths = true;
      continue;
    }
    if (!inPaths) {
      continue;
    }
    if (/^[^\s]/u.test(line) && !/^paths:\s*$/u.test(line)) {
      finishOperation();
      break;
    }
    const pathMatch = line.match(/^  (?:("[^"]+")|(\/[^:]+)):\s*$/u);
    if (pathMatch) {
      finishOperation();
      currentPath = pathMatch[1] ? JSON.parse(pathMatch[1]) : pathMatch[2];
      continue;
    }
    const methodMatch = line.match(/^    ([a-z]+):\s*$/u);
    if (methodMatch && OPENAPI_METHODS.has(methodMatch[1])) {
      finishOperation();
      currentOperation = {
        method: methodMatch[1].toUpperCase(),
        path: currentPath,
        requestSchema: null,
        responseSchema: null,
        routeKind: null,
      };
      continue;
    }
    if (!currentOperation) {
      continue;
    }
    const responseSchemaMatch = line.match(
      /^\s+x-zinuto-runtime-response-schema:\s*([A-Za-z0-9_]+)\s*$/u,
    );
    if (responseSchemaMatch) {
      currentOperation.responseSchema = responseSchemaMatch[1];
      continue;
    }
    const requestSchemaMatch = line.match(
      /^\s+x-zinuto-runtime-request-schema:\s*([A-Za-z0-9_]+)\s*$/u,
    );
    if (requestSchemaMatch) {
      currentOperation.requestSchema = requestSchemaMatch[1];
      continue;
    }
    const routeKindMatch = line.match(
      /^\s+x-zinuto-route-kind:\s*([A-Za-z0-9_-]+)\s*$/u,
    );
    if (routeKindMatch) {
      currentOperation.routeKind = routeKindMatch[1];
    }
  }
  finishOperation();
  return operations;
};

const toRouteKey = (routePath) => {
  const tokens = routePath
    .replace(/^\/api\/v1\/?/u, "")
    .replace(/^\/v1\/?/u, "")
    .split("/")
    .filter(Boolean)
    .map((token) =>
      token
        .replace(/[{}]/gu, "")
        .replace(/[^A-Za-z0-9]+/gu, " ")
        .trim()
        .split(/\s+/u)
        .filter(Boolean)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join(""),
    )
    .filter(Boolean);
  const candidate = tokens.join("");
  return candidate ? candidate.charAt(0).toLowerCase() + candidate.slice(1) : "root";
};

const buildRoutesObject = (paths) => {
  const usedKeys = new Map();
  return paths.map((routePath) => {
    const baseKey = toRouteKey(routePath);
    const seenCount = usedKeys.get(baseKey) ?? 0;
    usedKeys.set(baseKey, seenCount + 1);
    const key = seenCount === 0 ? baseKey : `${baseKey}${seenCount + 1}`;
    return { key, path: routePath };
  });
};

const buildApiOutput = ({
  basePath,
  basePathConstName,
  openApiSourceLabel,
  pathConstName,
  pathTypeName,
  paths,
  routeConstName,
}) => {
  const routes = buildRoutesObject(paths);
  return `// SPDX-License-Identifier: GPL-3.0-only
// This file is generated by tools/contracts/generate-openapi-contracts.mjs.
// Do not edit by hand; update ${openApiSourceLabel} and regenerate.

export const ${basePathConstName} = ${JSON.stringify(basePath)} as const;

export const ${pathConstName} = ${JSON.stringify(paths, null, 2)} as const;
export type ${pathTypeName} = (typeof ${pathConstName})[number];

export const ${routeConstName} = {
${routes
  .map(({ key, path: routePath }) => `  ${key}: ${JSON.stringify(routePath)},`)
  .join("\n")}
} as const satisfies Record<string, ${pathTypeName}>;
`;
};

const operationKey = ({ method, path: routePath }) => `${method} ${routePath}`;

const toRuntimePath = (routePath) => routePath.replace(/\{([^}]+)\}/gu, ":$1");

const buildSchemaBindings = (operations, schemaField) =>
  Object.fromEntries(
    operations
      .filter((operation) => operation[schemaField])
      .map((operation) => [operationKey(operation), operation[schemaField]]),
  );

const buildRuntimeSchemaOutput = (desktopLocalOperations) => {
  const payload = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    version: "v1",
    description:
      "Runtime Zod schema bindings for high-risk Zinuto v1 response payloads. OpenAPI owns route shape and envelope semantics; these bindings point to the shared field-level validators used by clients and tests.",
    services: {
      "desktop-local-api": {
        schemaModules: ["@zinuto/shared/contracts-desktop/api"],
        responseSchemas: buildSchemaBindings(desktopLocalOperations, "responseSchema"),
        requestSchemas: buildSchemaBindings(desktopLocalOperations, "requestSchema"),
      },
    },
  };
  return `${JSON.stringify(payload, null, 2)}\n`;
};

const dedupe = (values) => [...new Set(values)];

const groupSchemaMapEntries = (operations, { schemaField, pathFilter }) => {
  const entries = [];
  const entryByPath = new Map();
  for (const operation of operations) {
    const schemaName = operation[schemaField];
    if (!schemaName || !pathFilter(operation)) {
      continue;
    }
    const runtimePath = toRuntimePath(operation.path);
    let entry = entryByPath.get(runtimePath);
    if (!entry) {
      entry = { path: runtimePath, schemas: [] };
      entryByPath.set(runtimePath, entry);
      entries.push(entry);
    }
    entry.schemas = dedupe([...entry.schemas, schemaName]);
  }
  return entries;
};

const formatSchemaExpression = (schemaNames) => {
  if (schemaNames.length === 1) {
    return schemaNames[0];
  }
  return schemaNames
    .slice(1)
    .reduce(
      (expression, schemaName) => `${expression}\n    .or(${schemaName})`,
      schemaNames[0],
    );
};

const buildSchemaMapBlock = (constName, entries) => `${GENERATED_SCHEMA_MAP_COMMENT}
export const ${constName} = {
${entries
  .map(
    ({ path: runtimePath, schemas }) =>
      `  ${JSON.stringify(runtimePath)}: ${formatSchemaExpression(schemas)},`,
  )
  .join("\n")}
} as const;`;

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");

const replaceGeneratedSchemaMapBlock = (sourceText, constName, entries) => {
  const pattern = new RegExp(
    `(?:${escapeRegExp(GENERATED_SCHEMA_MAP_COMMENT)}\\n)?export const ${constName} = \\{[\\s\\S]*?\\n\\} as const;`,
    "u",
  );
  if (!pattern.test(sourceText)) {
    throw new Error(
      `[openapi-contracts] could not find ${constName} in shared runtime API schema maps.`,
    );
  }
  return sourceText.replace(pattern, buildSchemaMapBlock(constName, entries));
};

const buildDesktopRuntimeApiOutput = (sourceText, desktopOperations) => {
  return [
    [
      "DESKTOP_LOCAL_RESPONSE_SCHEMAS",
      groupSchemaMapEntries(desktopOperations, {
        schemaField: "responseSchema",
        pathFilter: () => true,
      }),
    ],
    [
      "DESKTOP_LOCAL_REQUEST_SCHEMAS",
      groupSchemaMapEntries(desktopOperations, {
        schemaField: "requestSchema",
        pathFilter: () => true,
      }),
    ],
  ].reduce(
    (output, [constName, entries]) =>
      replaceGeneratedSchemaMapBlock(output, constName, entries),
    sourceText,
  );
};

const buildOutputs = () => {
  const desktopDocument = readOpenApiDocument(DESKTOP_OPENAPI_PATH);
  const desktopText = desktopDocument.sourceText;
  const desktopLocalOperations = extractOpenApiOperations(desktopText);
  const desktopLocalPaths = extractOpenApiPaths(desktopText);
  return [
    {
      path: DESKTOP_OUTPUT_PATH,
      label: "packages/shared/src/contracts-desktop/http-api.ts",
      output: buildApiOutput({
        basePath: extractBasePath(desktopText, "/api/v1"),
        basePathConstName: "DESKTOP_LOCAL_API_BASE_PATH",
        openApiSourceLabel: "contracts/openapi/desktop-local-api.v1.yaml",
        pathConstName: "DESKTOP_LOCAL_API_PATHS",
        pathTypeName: "DesktopLocalApiPath",
        paths: desktopLocalPaths,
        routeConstName: "DESKTOP_LOCAL_API_ROUTES",
      }),
    },
    {
      path: RUNTIME_SCHEMA_OUTPUT_PATH,
      label: "contracts/runtime-response-schemas.v1.json",
      output: buildRuntimeSchemaOutput(desktopLocalOperations),
    },
    {
      path: DESKTOP_API_PATH,
      label: "packages/shared/src/contracts-desktop/api.ts",
      output: buildDesktopRuntimeApiOutput(
        readText(DESKTOP_API_PATH),
        desktopLocalOperations,
      ),
    },
    {
      path: DESKTOP_OPENAPI_ZOD_OUTPUT_PATH,
      label: "packages/shared/src/contracts-desktop/openapi-zod.generated.ts",
      output: buildOpenApiZodModule({
        spec: desktopDocument.spec,
        serviceName: "desktop-local-api",
      }),
    },
  ];
};

const outputs = buildOutputs();

if (checkOnly) {
  const staleOutputs = outputs.filter(({ path: outputPath, output }) => {
    const current = fs.existsSync(outputPath) ? readText(outputPath) : "";
    return current !== output;
  });
  if (staleOutputs.length) {
    throw new Error(
      [
        "[openapi-contracts] generated OpenAPI contract artifacts are out of date. Run npm run contract:generate.",
        ...staleOutputs.map(({ label }) => `- ${label}`),
      ].join("\n"),
    );
  }
  console.log("[openapi-contracts] generated OpenAPI contract artifacts are current.");
} else {
  for (const { path: outputPath, output } of outputs) {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, output, "utf8");
  }
  console.log(
    "[openapi-contracts] generated OpenAPI contract artifacts.",
  );
}
