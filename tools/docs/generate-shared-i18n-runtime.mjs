import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readI18nMessageSources } from "./i18n-message-source-utils.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "../..");
const sharedRoot = path.join(projectRoot, "packages", "shared", "src");
const outputPath = path.join(sharedRoot, "i18n.generated.ts");
const metadataOutputPath = path.join(sharedRoot, "i18n.metadata.generated.ts");
const loadersOutputPath = path.join(sharedRoot, "i18n.loaders.generated.ts");

const {
  catalogs,
  localeEntries,
  namespaceEntries,
  messageIds,
} = readI18nMessageSources({
  projectRoot,
});

const removeStaleGeneratedCatalogs = () => {
  for (const entry of fs.readdirSync(sharedRoot, { withFileTypes: true })) {
    if (
      entry.isFile() &&
      /^i18n\.generated\..+\.ts$/u.test(entry.name)
    ) {
      // Multiple release checks can generate the same catalogs concurrently.
      // A sibling generator may remove this stale file after readdirSync(),
      // which is harmless because every invocation writes the full catalog set.
      fs.rmSync(path.join(sharedRoot, entry.name), { force: true });
    }
  }
};

const toCatalogExportName = (locale) =>
  `I18N_CATALOG_${locale.replace(/[^a-z0-9]/giu, "_").toUpperCase()}`;

removeStaleGeneratedCatalogs();

const catalogImports = [];
const catalogEntries = [];
const catalogLoaderEntries = [];

for (const locale of localeEntries) {
  const exportName = toCatalogExportName(locale);
  const fileName = `i18n.generated.${locale}.ts`;
  const localeOutputPath = path.join(sharedRoot, fileName);
  const serializedLocaleCatalog = JSON.stringify(JSON.stringify(catalogs[locale] ?? {}));
  const localeOutput = `// SPDX-License-Identifier: GPL-3.0-only
/* eslint-disable */
// This file is generated by ./tools/docs/generate-shared-i18n-runtime.mjs.

export const ${exportName} = JSON.parse(
  ${serializedLocaleCatalog},
) as Record<string, Record<string, string>>;
`;
  fs.writeFileSync(localeOutputPath, localeOutput);
  catalogImports.push(`import { ${exportName} } from "./i18n.generated.${locale}.js";`);
  catalogEntries.push(`${JSON.stringify(locale)}: ${exportName}`);
  catalogLoaderEntries.push(
    `${JSON.stringify(locale)}: async () => (await import("./i18n.generated.${locale}.js")).${exportName}`,
  );
}

const metadataOutput = `// SPDX-License-Identifier: GPL-3.0-only
/* eslint-disable */
// This file is generated by ./tools/docs/generate-shared-i18n-runtime.mjs.

export const I18N_CATALOG_NAMESPACES = ${JSON.stringify(namespaceEntries)} as const;
export const I18N_SOURCE_LOCALES = ${JSON.stringify(localeEntries)} as const;
export const I18N_MESSAGE_IDS = ${JSON.stringify(messageIds)} as const;
`;

const output = `// SPDX-License-Identifier: GPL-3.0-only
/* eslint-disable */
// This file is generated by ./tools/docs/generate-shared-i18n-runtime.mjs.

${catalogImports.join("\n")}

export {
  I18N_CATALOG_NAMESPACES,
  I18N_MESSAGE_IDS,
  I18N_SOURCE_LOCALES,
} from "./i18n.metadata.generated.js";

export const I18N_CATALOGS = {
  ${catalogEntries.join(",\n  ")}
} as Record<string, Record<string, Record<string, string>>>;
`;

const loadersOutput = `// SPDX-License-Identifier: GPL-3.0-only
/* eslint-disable */
// This file is generated by ./tools/docs/generate-shared-i18n-runtime.mjs.

export const I18N_CATALOG_LOADERS = {
  ${catalogLoaderEntries.join(",\n  ")}
} as const;
`;

fs.writeFileSync(metadataOutputPath, metadataOutput);
fs.writeFileSync(outputPath, output);
fs.writeFileSync(loadersOutputPath, loadersOutput);
console.log(`[i18n] Generated ${path.relative(projectRoot, outputPath)}`);
