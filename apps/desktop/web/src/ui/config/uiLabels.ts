export type UiLabelKey = (typeof UI_LABEL_KEYS)[number];
export type UiLabelEntry = Record<UiLabelKey, string>;

const LANGUAGE_OPTION_MESSAGE_KEY_BY_LANGUAGE: Record<AppUiLanguage, string> = {
  en: 'uiLabels.languageOptions.en',
  'zh-CN': 'uiLabels.languageOptions.zhCn',
  ja: 'uiLabels.languageOptions.ja',
  ko: 'uiLabels.languageOptions.ko',
  es: 'uiLabels.languageOptions.es',
};

export const getLanguageOptions = (
  language: AppUiLanguage,
): Array<{ key: AppUiLanguage; label: string }> =>
  ([...APP_UI_LANGUAGES] as AppUiLanguage[]).map((key) => ({
    key,
    label: formatMessage(
      language,
      LANGUAGE_OPTION_MESSAGE_KEY_BY_LANGUAGE[key] as never,
    ),
  }));

export const getUiLabels = (language: AppUiLanguage): UiLabelEntry =>
  normalizeTradingCopyTree(
    language,
    Object.fromEntries(
      UI_LABEL_KEYS.map((key) => [
        key,
        formatMessage(language, `uiLabels.ui.${key}` as never),
      ]),
    ) as UiLabelEntry,
  );
