const SPECIAL_TRAINING_CONTENT_BY_LANGUAGE: Record<
  AppUiLanguage,
  SpecialTrainingPageContent
> = buildLocalizedRecord((language) =>
  parseUiConfigJsonBundle(
    language,
    "specialTraining.bundle",
    SPECIAL_TRAINING_CONTENT_BASE,
  ),
);

export const getSpecialTrainingPageContent = (
  language: AppUiLanguage,
): SpecialTrainingPageContent =>
  SPECIAL_TRAINING_CONTENT_BY_LANGUAGE[language] ??
  SPECIAL_TRAINING_CONTENT_BASE;

