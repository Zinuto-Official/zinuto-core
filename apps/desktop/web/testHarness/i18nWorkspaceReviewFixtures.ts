const buildPreviewHistorySummary = ({
  initialAsset,
  endingAsset,
  totalTrades,
  tradingCost,
  totalPnl,
  profitRate,
  maxDrawdownRate,
  startDate,
  endDate,
}: {
  initialAsset: number;
  endingAsset: number;
  totalTrades: number;
  tradingCost: number;
  totalPnl: number;
  profitRate: number;
  maxDrawdownRate: number;
  startDate: string;
  endDate: string;
}) => ({
  initialAsset,
  endingAsset,
  assetReturnRate: profitRate,
  durationDays: 5,
  startDate,
  endDate,
  buyCount: Math.max(1, totalTrades),
  sellCount: Math.max(1, totalTrades),
  totalTrades,
  investedAmount: initialAsset,
  tradingCost,
  realizedPnl: totalPnl,
  unrealizedPnl: 0,
  totalPnl,
  profitRate,
  maxDrawdownRate,
  maxDrawdownAmount: initialAsset * maxDrawdownRate,
});

